"""Run form B over the scenarios against the REAL verbs (dry-run) and write the traces.

    /tmp/spike/venv-python_statemachine/bin/python scratch/b-vs-c-spike/b_statemachine/run_scenarios.py
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))

from common.services import SCENARIOS, Services  # noqa: E402
from p1_dispatch import P1Dispatch  # noqa: E402

OUT = HERE / "out"

# model-only scenarios: nothing in the code produces these events (the HOLES), so the model is
# DRIVEN to the interrupt after a clean launch. They test the diagram, not the code.
SYNTHETIC = {"M1-reaped": "lane_reaped", "M2-end-early": "lane_ended_early"}


def run(name: str) -> dict:
    base = "S1-clean" if name in SYNTHETIC else name
    svc = Services(SCENARIOS[base])
    t0 = time.time()
    try:
        sm = P1Dispatch(svc)
        sm.send("go")
        if "running" in sm.configuration_values:
            sm.send(SYNTHETIC.get(name, "lane_handback"))
        end = [s for s in sm.configuration][0].id
        oracle = svc.oracle() if SCENARIOS[base].expect_oracle and name not in SYNTHETIC else None
        return {"scenario": name, "end": end, "trace": sm.trace, "verbs": svc.calls, "oracle": oracle,
                "seconds": round(time.time() - t0, 1)}
    finally:
        svc.close()


def main() -> int:
    OUT.mkdir(exist_ok=True)
    names = [*SCENARIOS, *SYNTHETIC]
    results = [run(n) for n in names]
    (OUT / "traces.json").write_text(json.dumps(results, indent=1), encoding="utf-8")
    lines = ["# Form B traces (python-statemachine) -- generated by run_scenarios.py", ""]
    for r in results:
        sc = SCENARIOS.get(r["scenario"]) or SCENARIOS["S1-clean"]
        want = "end_launched" if r["scenario"] in SYNTHETIC and False else sc.expect_end
        if r["scenario"] in SYNTHETIC:
            want = "end_reaped" if r["scenario"] == "M1-reaped" else "end_early"
        ok = r["end"] == want
        orc = r["oracle"]
        agree = "n/a" if not orc else ("AGREE" if (
            (orc["outcome"], r["end"]) in {("launched", "end_launched"), ("already-launched", "end_already_launched"),
                                           ("refused", "end_refused")}) else "DISAGREE")
        lines += [f"## {r['scenario']}: end={r['end']} (expected {want}: {'OK' if ok else 'MISMATCH'}); "
                  f"oracle launch_lane: {orc['outcome'] + ' exit ' + str(orc['exit']) if orc else 'n/a'} -> {agree}; "
                  f"{r['seconds']}s", ""]
        lines += [f"- {t['n']:>2}. {t['node']} [{t['kind']}, {t['actor']}/{t['zone']}] {json.dumps(t.get('result', ''))}"
                  for t in r["trace"]]
        lines += ["", "verbs run: " + "; ".join(f"{v['verb']} -> exit {v['exit']}" for v in r["verbs"]), ""]
    (OUT / "traces.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0 if all(r["end"] for r in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
