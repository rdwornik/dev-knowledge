"""The scenario driver and trace writer both forms share (so the forms differ only in the model)."""
from __future__ import annotations

import json
from pathlib import Path

from common.services import SCENARIOS

SYNTHETIC = {"M1-reaped": "lane_reaped", "M2-end-early": "lane_ended_early"}
EXPECT = {**{k: v.expect_end for k, v in SCENARIOS.items()}, "M1-reaped": "end_reaped", "M2-end-early": "end_early"}
AGREE = {("launched", "end_launched"), ("already-launched", "end_already_launched"), ("refused", "end_refused"),
         ("unresolved", "end_unresolved")}


def base(name: str) -> str:
    return "S1-clean" if name in SYNTHETIC else name


def write(title: str, results: list[dict], out: Path) -> bool:
    out.mkdir(exist_ok=True)
    (out / "traces.json").write_text(json.dumps(results, indent=1), encoding="utf-8")
    lines = [f"# {title} -- generated by run_scenarios.py", ""]
    good = True
    for r in results:
        want, orc = EXPECT[r["scenario"]], r["oracle"]
        ok = r["end"] == want
        good &= ok
        agree = "n/a" if not orc else ("AGREE" if (orc["outcome"], r["end"]) in AGREE else "DISAGREE")
        good &= agree != "DISAGREE"
        lines += [f"## {r['scenario']}: end={r['end']} (expected {want}: {'OK' if ok else 'MISMATCH'}); "
                  f"oracle launch_lane: {orc['outcome'] + ' exit ' + str(orc['exit']) if orc else 'n/a'} -> {agree}; "
                  f"{r['seconds']}s", ""]
        lines += [f"- {t['n']:>2}. {t['node']} [{t['kind']}, {t['actor']}/{t['zone']}] {json.dumps(t.get('result', ''))}"
                  for t in r["trace"]]
        lines += ["", "verbs run: " + "; ".join(f"{v['verb']} -> exit {v['exit']}" for v in r["verbs"]), ""]
    (out / "traces.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(l for l in lines if l.startswith("## ")))
    return good
