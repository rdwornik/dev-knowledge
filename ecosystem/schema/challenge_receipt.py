"""The CHALLENGE sub-stage receipt -- pydantic models, and the JSON Schema file generated from them.

Built by lane `lane-bu-1535-outer-loop` (`[#1535]` Done-when (6), R76). A new idea is challenged
by a reviewer of ANOTHER vendor before it becomes a row; the verdict is a receipt, not prose, so
the distiller can refuse on it mechanically.

TWO FORMS OF ONE CONTRACT. `ChallengeReceipt` below is the source; `challenge-receipt.schema.json`
beside this file is GENERATED by `json_schema()` and never hand-edited (`--check` exits 1 on
drift). `ChallengePayload` is the smaller object a reviewer writes to `$PHASE_PAYLOAD`; the
harness fills the rest of the receipt itself.

WHAT THE VALIDATORS REFUSE, because each is a way a challenge could pass without being one:

* a reviewer of the producer's own vendor -- that is self-review;
* AGREE / AMEND with no reviewer -- a pass needs a reviewer, and no reachable reviewer is
  INPUT_REQUIRED, never a pass;
* DISAGREE / INPUT_REQUIRED with `row_state` "proceed" (and the converse) -- the two fields
  state one fact;
* a non-empty `matrix_defects` -- a receipt cannot carry an unmeasured decision matrix.

A schema module never imports `scripts/`; the dependency runs the other way.

Run `uv run --locked python -m ecosystem.schema.challenge_receipt --write` after changing a model,
then commit the regenerated file with it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Annotated, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, model_validator

#: The generated JSON Schema file.
SCHEMA_FILE = Path(__file__).resolve().with_name("challenge-receipt.schema.json")

#: 1.0.0 -- first version (lane-bu-1535-outer-loop).
SCHEMA_VERSION = "1.0.0"

Verdict = Literal["AGREE", "AMEND", "DISAGREE", "INPUT_REQUIRED"]
RowState = Literal["proceed", "INPUT_REQUIRED"]

_Hex64 = Annotated[str, StringConstraints(strict=True, pattern=r"^[0-9a-f]{64}$")]
_Nonce = Annotated[str, StringConstraints(strict=True, min_length=8)]


class ChallengePayload(BaseModel):
    """What a reviewer writes: the nonce and input hash echo the ones it was handed."""

    model_config = ConfigDict(extra="forbid")

    nonce: _Nonce
    input_hash: _Hex64
    verdict: Literal["AGREE", "AMEND", "DISAGREE"]
    reasons: list[str] = []
    amendments: list[str] = []


class ChallengeReceipt(BaseModel):
    """The harness's record of one challenge."""

    model_config = ConfigDict(
        extra="forbid", populate_by_name=True, title="ChallengeReceipt",
        json_schema_extra={
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "description": "CHALLENGE receipt, schema " + SCHEMA_VERSION
                           + " (ecosystem/schema/challenge_receipt.py; generated, never hand-edited; [#1535]).",
        })

    schema_: str = Field(default="challenge-receipt/1", alias="schema")
    idea_sha256: _Hex64
    title: str
    proposes: str = ""
    decision_class: bool = True
    verdict: Verdict
    row_state: RowState
    producer_vendor: str
    reviewer_vendor: Optional[str]
    served_model: Optional[str]
    nonce: Optional[str]
    evidence: list[str] = []
    duplicates: list[str] = []
    matrix_defects: list[str] = []

    @model_validator(mode="after")
    def _a_challenge_is_a_challenge(self) -> "ChallengeReceipt":
        if self.reviewer_vendor is not None and self.reviewer_vendor == self.producer_vendor:
            raise ValueError(f"reviewer_vendor {self.reviewer_vendor!r} is the producer's own "
                             "vendor: a challenge from the producer's vendor is self-review")
        blocked = self.verdict in ("DISAGREE", "INPUT_REQUIRED")
        if blocked != (self.row_state == "INPUT_REQUIRED"):
            raise ValueError(f"verdict {self.verdict} and row_state {self.row_state} disagree: "
                             "DISAGREE / INPUT_REQUIRED <=> INPUT_REQUIRED")
        if self.verdict in ("AGREE", "AMEND") and self.reviewer_vendor is None:
            raise ValueError(f"verdict {self.verdict} needs a reviewer_vendor: a pass needs a "
                             "reviewer")
        if self.verdict == "INPUT_REQUIRED" and self.reviewer_vendor is not None:
            raise ValueError("verdict INPUT_REQUIRED means no reviewer was reached; "
                             "reviewer_vendor must be null")
        if self.matrix_defects:
            raise ValueError("a receipt cannot carry an unmeasured matrix: matrix_defects "
                             f"{self.matrix_defects}")
        return self


def json_schema() -> dict:
    """The JSON Schema of `ChallengeReceipt` -- exactly what `SCHEMA_FILE` holds."""
    return ChallengeReceipt.model_json_schema(by_alias=True)


def render_json_schema() -> str:
    """The file's bytes: two-space indented, one trailing newline."""
    return json.dumps(json_schema(), indent=2, ensure_ascii=False) + "\n"


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m ecosystem.schema.challenge_receipt",
                                     description="Write or check challenge-receipt.schema.json.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the schema file")
    mode.add_argument("--check", action="store_true", help="exit 1 if the file has drifted")
    args = parser.parse_args(argv)
    text = render_json_schema()
    if args.write:
        SCHEMA_FILE.write_text(text, encoding="utf-8", newline="\n")
        return 0
    try:
        current = SCHEMA_FILE.read_text(encoding="utf-8")
    except OSError:
        current = ""
    if current != text:
        sys.stderr.write(f"{SCHEMA_FILE.name} has drifted from ChallengeReceipt; run --write\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
