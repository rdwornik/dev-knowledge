"""The DISTILL receipt -- pydantic models, and the JSON Schema file generated from them.

Built by lane `lane-bu-1535-outer-loop` (`[#1535]` Done-when (5)). The distiller is the front
stage of a phased row: it scores every NEW path a plan proposes against the organ index and
`why`, and emits this receipt. The receipt REFUSES a NEW path that has a reuse candidate unless
it carries a NEW-JUSTIFIED line AND a CHALLENGE from a vendor other than the producer that
AGREEs or AMENDs -- reuse is the default, and building new needs a second vendor's agreement.

TWO FORMS OF ONE CONTRACT. `DistillReceipt` below is the source; `distill-receipt.schema.json`
beside this file is GENERATED by `json_schema()` and never hand-edited (`--check` exits 1 on
drift).

`BASELINE` names the constraint ids every distilled prompt must carry; it lives here because a
schema module never imports `scripts/`, and the generator imports it from here instead.

Run `uv run --locked python -m ecosystem.schema.distill_receipt --write` after changing a model,
then commit the regenerated file with it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, model_validator

from ecosystem.schema.challenge_receipt import ChallengeReceipt

#: The generated JSON Schema file.
SCHEMA_FILE = Path(__file__).resolve().with_name("distill-receipt.schema.json")

#: 1.0.0 -- first version (lane-bu-1535-outer-loop).
SCHEMA_VERSION = "1.0.0"

#: Constraint ids every distilled prompt carries.
BASELINE: tuple[str, ...] = ("C-TASK", "C-SCOPE", "C-RED", "C-VENDOR", "C-CLEAN")


def _norm(text: str) -> str:
    return text.replace("`", "").strip()


def _names(proposed: str, path: str) -> bool:
    """True when the normalised `proposes` is this path, or shares its file stem."""
    want = _norm(path)
    if not proposed or not want:
        return False
    stem = lambda s: s.replace("\\", "/").rsplit("/", 1)[-1].rsplit(".", 1)[0]  # noqa: E731
    return proposed == want or stem(proposed) == stem(want)


class ReuseCandidate(BaseModel):
    """An existing path that resembles a NEW path the plan proposes."""

    model_config = ConfigDict(extra="forbid")

    path: str
    source: Literal["organ-index", "why"]
    score: float = Field(ge=0, le=1)
    matched: str
    purpose: str = ""


class PhasePlan(BaseModel):
    """One phase of the row's plan: which vendor, model and effort run it."""

    model_config = ConfigDict(extra="forbid")

    id: str
    model: Optional[str]
    effort: Optional[str]
    vendor: str


class DistillReceipt(BaseModel):
    """The distiller's record for one row."""

    model_config = ConfigDict(
        extra="forbid", populate_by_name=True, title="DistillReceipt",
        json_schema_extra={
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "description": "DISTILL receipt, schema " + SCHEMA_VERSION
                           + " (ecosystem/schema/distill_receipt.py; generated, never hand-edited).",
        })

    schema_: str = Field(default="distill-receipt/1", alias="schema")
    row: str
    row_phase: str
    title: str
    reuse_candidates: list[ReuseCandidate] = []
    reuse_threshold: float = 0.5
    dependencies: list[str] = []
    skills_commands: list[str] = []
    phases: list[PhasePlan] = []
    constraints: list[str]
    boosted_prompt: str
    plan_new_paths: list[str] = []
    new_justified: Optional[str] = None
    producer_vendor: str
    challenge: Optional[ChallengeReceipt] = None
    row_state: Literal["ready", "INPUT_REQUIRED"] = "ready"

    @model_validator(mode="after")
    def _reuse_is_the_default(self) -> "DistillReceipt":
        missing = [c for c in BASELINE if c not in self.constraints]
        if missing:
            raise ValueError(f"constraints lack the baseline id(s) {missing}")
        proposed = _norm(self.challenge.proposes) if self.challenge is not None else ""
        for path in self.plan_new_paths:
            hits = [c for c in self.reuse_candidates
                    if c.matched == path and c.score >= self.reuse_threshold]
            if not hits:
                continue
            ch = self.challenge
            if not (self.new_justified and self.new_justified.strip()):
                raise ValueError(f"NEW path {path} has reuse candidate {hits[0].path} but no "
                                 "new_justified line")
            if (ch is None or ch.reviewer_vendor is None
                    or ch.reviewer_vendor == self.producer_vendor
                    or ch.verdict not in ("AGREE", "AMEND")):
                raise ValueError(f"NEW path {path} has reuse candidate {hits[0].path} and needs "
                                 "an AGREE/AMEND challenge from a vendor other than the producer")
            if not _names(proposed, path):
                raise ValueError(f"NEW path {path} is not the path the challenge proposes "
                                 f"({ch.proposes!r}); every conflicting NEW path needs its own")
        if self.challenge is not None and self.challenge.row_state == "INPUT_REQUIRED":
            if self.row_state != "INPUT_REQUIRED":
                raise ValueError("the challenge is INPUT_REQUIRED, so row_state must be too")
        return self


def json_schema() -> dict:
    """The JSON Schema of `DistillReceipt` -- exactly what `SCHEMA_FILE` holds."""
    return DistillReceipt.model_json_schema(by_alias=True)


def render_json_schema() -> str:
    """The file's bytes: two-space indented, one trailing newline."""
    return json.dumps(json_schema(), indent=2, ensure_ascii=False) + "\n"


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m ecosystem.schema.distill_receipt",
                                     description="Write or check distill-receipt.schema.json.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the schema file")
    mode.add_argument("--check", action="store_true", help="exit 1 if the file has drifted")
    args = parser.parse_args(argv)
    text = render_json_schema()
    if args.write:
        SCHEMA_FILE.write_text(text, encoding="utf-8", newline="\n")
        return 0
    try:
        current = SCHEMA_FILE.read_text(encoding="utf-8")
    except OSError:
        current = ""
    if current != text:
        sys.stderr.write(f"{SCHEMA_FILE.name} has drifted from DistillReceipt; run --write\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
