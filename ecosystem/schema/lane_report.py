"""The section-3 LANE REPORT contract -- pydantic models, and the JSON Schema file generated from them.

Source: `to-browser/DIGEST-PROPOSAL-ADR-LANE-REPORT-CONTRACT-2026-10-11.md` section 3 (the JSON
shape and its field rules), adopted by R96 D1; built by lane `lane-bw-1368-lane-report-rollup`
(`[#1368]` nearest). A lane ends with ONE machine-validated JSON object, not prose.

TWO FORMS OF ONE CONTRACT, AND WHICH ONE IS THE SOURCE. `LaneReport` below is the source.
`lane-report.schema.json`, beside this file, is its JSON Schema, GENERATED by `json_schema()` and
never hand-edited; `tests/test_lane_digest.py` asserts the committed file equals the generated
one. The file is what a headless `claude -p` receives as `--json-schema` (`scripts/dispatch.py`
`build_plan`, the streamed head), so the CLI enforces the shape at the producer; the model is what
the batch rollup (`scripts/lane_digest.py --manifest`) validates a received report with. Validation
uses `pydantic`, already in `uv.lock` -- `jsonschema` is not, and no dependency is added.

THE THREE RULES THE DONE-CONTRACT NAMES, and where each lives in both forms:

* `state` is REQUIRED (no default) -- the model's required field / the schema's `required`.
* `state` is a CLOSED enum, A2A v1.0's task-state vocabulary -- a `Literal` / an `enum`.
* THE VACUOUS-PASS RULE (S-56 Done 4c): a report whose `checks` are all `NOT_RUN` cannot be
  `COMPLETED`. "All" includes an empty list -- no check at all passes nothing either. The model's
  `_no_vacuous_completed` validator / the schema's `allOf[0]` `if state == COMPLETED then checks
  contains a PASS or FAIL`.

FIELDS BEYOND SECTION 3, admitted on measurement. Every F1 LANE-END of batch BW (the first reports
written in this shape, on the transport 2026-10-13) carries `intent_met.note` -- the architect's
R99.2 one-liner -- and a top-level `review` (the Codex verdict, served model, session and nonce,
R59), or `review: null` on a docs-only lane. Both are declared here so `extra="forbid"` still turns
a misspelled key into a refusal rather than silently inert data.

Run `uv run --locked python -m ecosystem.schema.lane_report --write` after changing a model, then
commit the regenerated file with it (`--check` exits 1 on drift).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Annotated, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, StrictInt, StringConstraints, model_validator

#: The generated JSON Schema file -- the one `claude -p --json-schema` receives.
SCHEMA_FILE = Path(__file__).resolve().with_name("lane-report.schema.json")

#: 1.0.0 -- first version (lane-bw-1368-lane-report-rollup, 2026-10-13).
SCHEMA_VERSION = "1.0.0"

State = Literal["COMPLETED", "FAILED", "REJECTED", "INPUT_REQUIRED", "CANCELED"]
STATES: tuple[str, ...] = State.__args__
Kind = Literal["code", "doc", "config", "research"]
CheckResult = Literal["PASS", "FAIL", "NOT_RUN"]

_Text = Annotated[str, StringConstraints(strict=True, min_length=1)]
_Unresolved = Annotated[str, StringConstraints(strict=True, min_length=1, max_length=120)]
_Sha = Annotated[str, StringConstraints(strict=True, pattern=r"^[0-9a-f]{7,40}$")]


class _Contract(BaseModel):
    """We own this grammar, so an unknown key is an error, never inert data."""

    model_config = ConfigDict(frozen=True, extra="forbid")


class Done(_Contract):
    """How many of the contract's Done items the lane met, out of how many."""

    met: StrictInt = Field(ge=0)
    total: StrictInt = Field(ge=0)

    @model_validator(mode="after")
    def _met_within_total(self) -> "Done":
        if self.met > self.total:
            raise ValueError(f"done.met {self.met} exceeds done.total {self.total}")
        return self


class Check(_Contract):
    """One check run on the lane. `NOT_RUN` is not a pass."""

    name: _Text
    how: Literal["deterministic", "llm"]
    result: CheckResult
    evidence: _Text


class Agent(_Contract):
    """Who did the work or the judging: vendor, served model, session id."""

    vendor: _Text
    model: _Text
    session: _Text


class IntentMet(_Contract):
    """The isolated evaluator's verdict. `UNSURE` is a first-class answer, never a pass."""

    verdict: Literal["YES", "NO", "UNSURE"]
    evaluator: Agent
    note: Optional[_Text] = None


class Evidence(_Contract):
    """Pointers to where the evidence lives; the narrative stays in git, CI and the transport."""

    branch: _Text
    check_run: Optional[_Text]
    audit: Optional[_Text]


class Review(_Contract):
    """The reviewer's own record (R59): served model, session id and the nonce it returned."""

    vendor: _Text
    model: _Text
    session: _Text
    verdict: Literal["APPROVE", "REQUEST-CHANGES"]
    nonce: _Text


#: The vacuous-pass rule as JSON Schema: a COMPLETED report holds at least one check that ran.
_VACUOUS_PASS_RULE = {
    "if": {"properties": {"state": {"const": "COMPLETED"}}, "required": ["state"]},
    "then": {"properties": {"checks": {"contains": {
        "type": "object", "properties": {"result": {"enum": ["PASS", "FAIL"]}},
        "required": ["result"]}}}},
}


class LaneReport(_Contract):
    """The section-3 LANE REPORT. Every section-3 field is required; null is an explicit value."""

    model_config = ConfigDict(
        frozen=True, extra="forbid", title="LaneReport",
        json_schema_extra={
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "description": "Section-3 LANE REPORT, schema " + SCHEMA_VERSION
                           + " (ecosystem/schema/lane_report.py; generated, never hand-edited).",
            "allOf": [_VACUOUS_PASS_RULE],
        })

    lane: _Text
    batch: _Text
    task: _Text
    kind: Kind
    state: State
    done: Done
    checks: list[Check]
    intent_met: Optional[IntentMet]
    unresolved: list[_Unresolved] = Field(max_length=3)
    operator_action: Optional[_Text]
    merged_sha: Optional[_Sha]
    producer: Agent
    cost_usd: Optional[float] = Field(ge=0)
    evidence: Evidence
    review: Optional[Review] = None

    @model_validator(mode="after")
    def _no_vacuous_completed(self) -> "LaneReport":
        if self.state == "COMPLETED" and all(c.result == "NOT_RUN" for c in self.checks):
            raise ValueError("state COMPLETED with every check NOT_RUN (or no check at all) is a "
                             "vacuous pass: NOT_RUN is not a pass (S-56 Done 4c)")
        return self


def json_schema() -> dict:
    """The JSON Schema of `LaneReport` -- exactly what `SCHEMA_FILE` holds."""
    return LaneReport.model_json_schema()


def render_json_schema() -> str:
    """The file's bytes: two-space indented, one trailing newline."""
    return json.dumps(json_schema(), indent=2, ensure_ascii=False) + "\n"


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m ecosystem.schema.lane_report",
                                     description="Write or check lane-report.schema.json.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the schema file")
    mode.add_argument("--check", action="store_true", help="exit 1 if the file has drifted")
    args = parser.parse_args(argv)
    text = render_json_schema()
    if args.write:
        SCHEMA_FILE.write_text(text, encoding="utf-8", newline="\n")
        return 0
    try:
        current = SCHEMA_FILE.read_text(encoding="utf-8")
    except OSError:
        current = ""
    if current != text:
        sys.stderr.write(f"{SCHEMA_FILE.name} has drifted from LaneReport; run --write\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
