"""The outer-loop PHASE PAYLOAD and PHASE RECEIPT contracts -- pydantic models, and the JSON Schema generated from them.

Built by lane `lane-bu-1535-outer-loop` (`[#1535]`). A phase is a spawned process the harness owns
(`scripts/run_phase.py`); the agent writes ONE small payload file, and the harness -- never the
agent -- writes the receipt around it.

TWO MODELS, TWO AUTHORS. `PhasePayload` is the ONLY thing an agent writes: a nonce, the input hash
it was handed, an outcome, findings. `PhaseReceipt` is built ONLY by the harness and carries every
fact an agent could otherwise forge. So the receipt DERIVES, and then re-checks:

* `vendor` is derived from the command's head (`vendor_for_argv`), through the `cli` field of
  `ecosystem/provider-registry.yaml`. A receipt whose `vendor` disagrees with its own `command`
  is refused -- a claude command cannot claim to be xai.
* `served_model` is derived from the CLI's own record (`served_model_from_record`), never from the
  payload, and must equal `model_reported` (one fact, two keys: the second is the dodo receipt key).
  A served model whose family does not fit the vendor is refused; a `local` vendor serves none.
* `payload_sha256` is the digest of the carried payload and is None without one; status COMPLETE
  requires a payload.

`RECEIPT_KEYS` is the ten-key set `scripts/dodo.py` `_RECEIPT_KEYS` already reads, so a receipt is
a superset of what dodo checks. The committed `phase-receipt.schema.json` is generated by
`json_schema()` (by alias, so the key is `schema`), never hand-edited; `--payload-schema` prints
the payload schema, which is what `claude -p --json-schema` receives. Validation uses `pydantic`,
already in `uv.lock`; no dependency is added.

Run `uv run --locked python -m ecosystem.schema.phase_receipt --write` after changing a model, then
commit the regenerated file with it (`--check` exits 1 on drift).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from functools import cache
from pathlib import Path
from typing import Annotated, Any, Literal, Optional

import yaml
from pydantic import BaseModel, ConfigDict, Field, StringConstraints, model_validator

#: The generated JSON Schema file.
SCHEMA_FILE = Path(__file__).resolve().with_name("phase-receipt.schema.json")

#: The provider registry `cli` -> vendor map is read from; absolute, so cwd never matters.
DEFAULT_REGISTRY = Path(__file__).resolve().parents[2] / "ecosystem" / "provider-registry.yaml"

#: 1.0.0 -- first version (lane-bu-1535-outer-loop, 2026-10-15).
SCHEMA_VERSION = "1.0.0"

Outcome = Literal["PASS", "FAIL", "ACCEPT", "REFUSE", "INPUT_REQUIRED"]
Severity = Literal["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]

#: Equals `scripts/dodo.py` `_RECEIPT_KEYS`; a dumped receipt carries every one.
RECEIPT_KEYS = ("schema", "organ", "status", "exit_code", "duration_ms", "input_hash",
                "model_requested", "model_reported", "command", "finished_at")

_Text = Annotated[str, StringConstraints(min_length=1)]
_Hex64 = Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")]

_EXTENSIONS = (".exe", ".cmd", ".ps1", ".bat")

#: vendor -> the pattern its served model's family must fit; `local` is handled apart (None only).
_FAMILIES: dict[str, re.Pattern[str]] = {
    "anthropic": re.compile(r"^claude-"),
    "openai": re.compile(r"^(gpt-|o\d|codex)"),
    "xai": re.compile(r"^grok-"),
    "google": re.compile(r"^gemini-"),
    "antigravity": re.compile(r"^gemini-"),
    "copilot-enterprise": re.compile(r"^(claude-|gpt-|gemini-)"),
}


class Finding(BaseModel):
    """One finding an agent reports."""

    model_config = ConfigDict(extra="forbid")

    id: _Text
    severity: Severity
    claim: _Text
    evidence: str = ""


class PhasePayload(BaseModel):
    """The ONLY thing an agent writes. Unknown keys are refused, never inert data."""

    model_config = ConfigDict(
        extra="forbid", title="PhasePayload",
        json_schema_extra={"$schema": "https://json-schema.org/draft/2020-12/schema"})

    nonce: str = Field(min_length=8)
    input_hash: _Hex64
    outcome: Outcome
    findings: list[Finding] = []
    detail: str = ""
    files_in_scope: list[str] = []
    red_test_ids: list[str] = []
    constraints_add: list[str] = []


class InputDigest(BaseModel):
    """One input file the phase was handed, and the digest it was handed at."""

    model_config = ConfigDict(extra="forbid")

    path: str
    sha256: _Hex64


@cache
def _cached_cli_vendors(registry: str) -> dict[str, str]:
    return load_cli_vendors(Path(registry))


def load_cli_vendors(registry: Path = DEFAULT_REGISTRY) -> dict[str, str]:
    """`providers.<key>.cli` -> `<key>`; a provider with a null `cli` is skipped."""
    data = yaml.safe_load(Path(registry).read_text(encoding="utf-8")) or {}
    return {str(spec["cli"]): key for key, spec in (data.get("providers") or {}).items()
            if isinstance(spec, dict) and spec.get("cli")}


def vendor_for_argv(argv: list[str], cli_vendors: Optional[dict[str, str]] = None) -> str:
    """The vendor of a command's head (basename, lower-cased, extension stripped); unknown -> local."""
    if cli_vendors is None:
        cli_vendors = _cached_cli_vendors(str(DEFAULT_REGISTRY))
    head = re.split(r"[\\/]", argv[0])[-1].lower() if argv else ""
    for ext in _EXTENSIONS:
        if head.endswith(ext):
            head = head[: -len(ext)]
            break
    return cli_vendors.get(head, "local")


def served_model_from_record(cli: Optional[str], record: Optional[dict]) -> Optional[str]:
    """The model the CLI itself says served the run, or None when its record does not say."""
    if not cli or not isinstance(record, dict):
        return None
    if cli == "claude":
        usage = record.get("modelUsage")
        if not isinstance(usage, dict) or not usage:
            return None

        def _out(item: tuple[str, Any]) -> int:
            val = item[1].get("outputTokens") if isinstance(item[1], dict) else 0
            return val if isinstance(val, int) else 0

        return max(usage.items(), key=_out)[0]
    key = {"codex": "model", "grok": "model", "copilot": "currentModel"}.get(cli)
    value = record.get(key) if key else None
    return value if isinstance(value, str) and value else None


def payload_sha256(payload: PhasePayload) -> str:
    """The digest of a payload, over its canonical JSON."""
    text = json.dumps(payload.model_dump(), sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


class PhaseReceipt(BaseModel):
    """Built ONLY by the harness. Every field an agent could forge is derived and re-checked here."""

    model_config = ConfigDict(
        extra="forbid", populate_by_name=True, title="PhaseReceipt",
        json_schema_extra={
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "description": "Outer-loop PHASE RECEIPT, schema " + SCHEMA_VERSION
                           + " (ecosystem/schema/phase_receipt.py; generated, never hand-edited; [#1535]).",
        })

    schema_: str = Field("phase-receipt/1", alias="schema")
    organ: str
    status: Literal["ok", "COMPLETE", "FAILED", "KILLED"]
    exit_code: Optional[int]
    duration_ms: int = Field(ge=0)
    input_hash: _Hex64
    model_requested: Optional[str]
    model_reported: Optional[str]
    command: list[str] = Field(min_length=1)
    finished_at: str
    row: str
    lane: str
    phase: str
    round: int = Field(ge=1, le=2)
    vendor: str
    cli_version: Optional[str]
    served_model: Optional[str]
    started_at: str
    inputs: list[InputDigest]
    nonce: str
    usage: Optional[dict]
    payload_sha256: Optional[_Hex64]
    payload: Optional[PhasePayload]
    substituted_from: Optional[str] = None

    @model_validator(mode="after")
    def _derived_facts_hold(self) -> "PhaseReceipt":
        expected = vendor_for_argv(self.command)
        if self.vendor != expected:
            raise ValueError(f"vendor {self.vendor!r} is forged: command {self.command[0]!r} "
                             f"derives vendor {expected!r}")
        if self.served_model != self.model_reported:
            raise ValueError(f"served_model {self.served_model!r} != model_reported "
                             f"{self.model_reported!r}")
        if self.served_model is not None:
            family = _FAMILIES.get(self.vendor)
            if family is None:
                raise ValueError(f"vendor {self.vendor!r} serves no model, got {self.served_model!r}")
            if not family.match(self.served_model):
                raise ValueError(f"served_model {self.served_model!r} does not fit vendor "
                                 f"{self.vendor!r}")
        if self.payload is None:
            if self.payload_sha256 is not None:
                raise ValueError("payload_sha256 is set but there is no payload")
            if self.status == "COMPLETE":
                raise ValueError("status COMPLETE requires a payload")
        elif self.payload_sha256 != payload_sha256(self.payload):
            raise ValueError("payload_sha256 does not match the carried payload")
        else:
            if self.payload.nonce != self.nonce:
                raise ValueError("payload nonce does not match the receipt nonce")
            if self.payload.input_hash != self.input_hash:
                raise ValueError("payload input_hash does not match the receipt input_hash")
        return self


def json_schema() -> dict:
    """The JSON Schema of `PhaseReceipt` -- exactly what `SCHEMA_FILE` holds."""
    return PhaseReceipt.model_json_schema(by_alias=True)


def render_json_schema() -> str:
    """The file's bytes: two-space indented, one trailing newline."""
    return json.dumps(json_schema(), indent=2, ensure_ascii=False) + "\n"


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m ecosystem.schema.phase_receipt",
                                     description="Write or check phase-receipt.schema.json.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the schema file")
    mode.add_argument("--check", action="store_true", help="exit 1 if the file has drifted")
    mode.add_argument("--payload-schema", action="store_true",
                      help="print the PhasePayload JSON Schema to stdout")
    args = parser.parse_args(argv)
    if args.payload_schema:
        sys.stdout.write(json.dumps(PhasePayload.model_json_schema(), indent=2) + "\n")
        return 0
    text = render_json_schema()
    if args.write:
        SCHEMA_FILE.write_text(text, encoding="utf-8", newline="\n")
        return 0
    try:
        current = SCHEMA_FILE.read_text(encoding="utf-8")
    except OSError:
        current = ""
    if current != text:
        sys.stderr.write(f"{SCHEMA_FILE.name} has drifted from PhaseReceipt; run --write\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
