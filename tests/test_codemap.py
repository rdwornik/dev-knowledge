CLI_MODULE = ["python", "-m", "codemap.cli"]
_ENV = {**os.environ, "PYTHONPATH": str(SCRIPTS_DIR)}


def _run_cli(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "codemap.cli", *args],
        capture_output=True,
        text=True,
        env=_ENV,
    )


def test_cli_generate_stdout():
    r = _run_cli("generate", str(SIMPLE_REPO))
    assert r.returncode == 0
    assert "| module | layer | path | flags |" in r.stdout
    assert "pkg_a" in r.stdout


def test_cli_generate_write(tmp_path):
    # Copy arch-clean fixture to a tmp location so --write can mutate it
    shutil.copytree(str(ARCH_CLEAN), str(tmp_path / "repo"))
    r = _run_cli("generate", str(tmp_path / "repo"), "--write")
    assert r.returncode == 0
    content = (tmp_path / "repo" / "ARCHITECTURE.md").read_text()
    assert "<!-- CODEMAP:START -->" in content
    assert "<!-- CODEMAP:END -->" in content
    assert "| module | layer | path | flags |" in content
    assert "<!-- generated by codemap tool; do not edit by hand -->" in content


def test_cli_generate_write_produces_text_block(tmp_path):
    # The block between the markers is compact text — no fence, no Mermaid
    # (ADR-51 amendment 2026-07-05).
    shutil.copytree(str(ARCH_CLEAN), str(tmp_path / "repo"))
    _run_cli("generate", str(tmp_path / "repo"), "--write")
    content = (tmp_path / "repo" / "ARCHITECTURE.md").read_text()
    start = content.index("<!-- CODEMAP:START -->") + len("<!-- CODEMAP:START -->")
    end = content.index("<!-- CODEMAP:END -->")
    block = content[start:end]
    assert "```" not in block
    assert "mermaid" not in block.lower()
    assert "| module | layer | path | flags |" in block
    assert "Dependencies (`from -> to`" in block
    assert "<!-- generated by codemap tool; do not edit by hand -->" in block


def test_cli_check_clean():
    r = _run_cli("check", str(ARCH_CLEAN))
    assert r.returncode == 0


def test_cli_check_drift():
    r = _run_cli("check", str(ARCH_DRIFT))
    assert r.returncode == 1


def test_cli_help():
    r = _run_cli("--help")
    assert r.returncode == 0
    assert "generate" in r.stdout
    assert "check" in r.stdout


def test_cli_arch_file_check_and_generate(tmp_path):
    # --arch-file targets a doc at a non-default path for both check and generate.
    shutil.copytree(str(ARCH_CLEAN), str(tmp_path / "repo"))
    repo = tmp_path / "repo"
    alt = repo / "ARCHITECTURE-ALT.md"
    (repo / "ARCHITECTURE.md").rename(alt)

    # check against the alt doc is clean (default would be exit 2 — missing)
    assert _run_cli("check", str(repo), "--arch-file", str(alt)).returncode == 0
    assert _run_cli("check", str(repo)).returncode == 2

    # generate --write targets the alt doc
    r = _run_cli("generate", str(repo), "--arch-file", str(alt), "--write")
    assert r.returncode == 0
    assert "<!-- CODEMAP:START -->" in alt.read_text()
    assert not (repo / "ARCHITECTURE.md").exists()
