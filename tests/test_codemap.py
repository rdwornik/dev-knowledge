def test_text_emit_no_fence_no_mermaid():
    out = emit_text(["pkg_a", "pkg_b"], [("pkg_a", "pkg_b")])
    assert "```" not in out
    assert "mermaid" not in out.lower()
    assert "<!-- generated by codemap tool; do not edit by hand -->" in out


def test_text_emit_module_table_and_dependency_list():
    out = emit_text(["pkg_a", "pkg_b"], [("pkg_a", "pkg_b")])
    assert "| module | layer | path | flags |" in out
    assert "| pkg_a | - | src/pkg_a/ | - |" in out
    assert "| pkg_b | - | src/pkg_b/ | - |" in out
    assert "- pkg_a -> pkg_b" in out


def test_text_emit_orphan_flag():
    out = emit_text(["pkg_a", "pkg_b", "pkg_c"], [("pkg_a", "pkg_b")])
    assert "| pkg_c | - | src/pkg_c/ | orphan |" in out


def test_text_emit_cycle_flag():
    out = emit_text(["pkg_a", "pkg_b"], [("pkg_a", "pkg_b"), ("pkg_b", "pkg_a")])
    assert "- pkg_a -> pkg_b [cycle]" in out
    assert "- pkg_b -> pkg_a [cycle]" in out


def test_text_emit_layers_and_source_root():
    layers = {"pkg_a": "core", "pkg_b": "foundation"}
    out = emit_text(["pkg_a", "pkg_b"], [("pkg_a", "pkg_b")], layers=layers,
                    source_root="scripts")
    assert "| pkg_a | core | scripts/pkg_a/ | - |" in out
    assert "| pkg_b | foundation | scripts/pkg_b/ | - |" in out
    assert "source root: `scripts/`" in out


def test_text_emit_empty_repo():
    out = emit_text([], [])
    assert "| (none) | - | - | - |" in out
    assert "- (none)" in out


def test_text_emit_deterministic():
    packages = ["pkg_b", "pkg_a"]
    edges = [("pkg_b", "pkg_a"), ("pkg_a", "pkg_b")]
    assert emit_text(packages, edges) == emit_text(packages, edges)


