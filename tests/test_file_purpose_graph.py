# --------------------------------------------------------------------------- THE REFUSAL
# Written first, RED first. Everything else in this file exists to keep it honest.


def test_why_refuses_a_planted_unknown_file(mini: Path):
    """A file nothing explains is a DEFECT, not a mystery — so `why` FAILs on it."""
    planted = _write(mini / "scripts" / "nothing_explains_me.py", "x = 1\n")
    graph = fpg.build(mini)
    with pytest.raises(fpg.UnknownFile) as excinfo:
        fpg.why(graph, planted.relative_to(mini).as_posix())
    assert excinfo.value.exists is True
    assert "nothing_explains_me.py" in str(excinfo.value)


def test_why_refuses_a_path_that_does_not_exist(mini: Path):
    """The other refusal flavour, distinguished rather than collapsed into the first."""
    graph = fpg.build(mini)
    with pytest.raises(fpg.UnknownFile) as excinfo:
        fpg.why(graph, "scripts/no_such_file_at_all.py")
    assert excinfo.value.exists is False


def test_cli_exits_nonzero_on_a_planted_unknown(mini: Path):
    """The refusal survives the CLI boundary — an exit code, not just an exception."""
    _write(mini / "scripts" / "nothing_explains_me.py", "x = 1\n")
    proc = subprocess.run(
        [sys.executable, str(_P), "why", "scripts/nothing_explains_me.py",
         "--repo-root", str(mini)],
        capture_output=True, text=True,
    )
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert "nothing explains" in (proc.stdout + proc.stderr).lower()


def test_cli_exits_zero_on_a_governed_file(mini: Path):
    proc = subprocess.run(
        [sys.executable, str(_P), "why", "protocols/PLAYBOOK.md", "--repo-root", str(mini)],
        capture_output=True, text=True,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "purpose" in proc.stdout.lower()
    assert "consumers" in proc.stdout.lower()
    assert "edges" in proc.stdout.lower()


def test_render_truncates_but_never_truncates_the_count(mini: Path):
    """A 787-edge answer is a scroll, not an answer — so rows truncate. The COUNT does not:
    it is the evidence, and a truncated count would be a lie rather than a summary."""
    graph = fpg.build(mini)
    answer = fpg.why(graph, "docs/audits/README.md")
    answer.edges = answer.edges * 30  # 30 rows from one real edge — shape, not a live count
    text = fpg.render(answer, limit=5)
    assert f"edges ({len(answer.edges)})" in text
    assert "25 more not shown" in text
    assert "25 more not shown" not in fpg.render(answer, limit=0)


