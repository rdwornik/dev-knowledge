"""Tests for scripts/file_purpose_graph.py — FPG-1, the file-purpose graph's first slice.

RED-FIRST, and the refusal came first. The contract's own words: *"Build the refusal first and
test it with a planted unknown; that is the RED-first witness for this lane."* So the first
test written was `test_why_refuses_a_planted_unknown_file`, and it was RED — with the whole
module absent — before a line of `file_purpose_graph.py` existed. A green test that never went
red proves the assertion runs, not that it discriminates.

THE FIXTURE REPO IS SYNTHETIC AND COMPLETE. Every structural test builds a miniature repo under
`tmp_path` carrying all five inputs in their REAL shapes (a `declaration_docs:` registry with a
live `<!-- rule: -->`/`# rule:` pair, a generated audits index, an audit citing `[#42]`, two
`tasks/` rows with a `depends-on` edge, a deploy manifest with a carrier and a component). That
is deliberate: pinning live counts would encode today's moment and break on the next commit,
which is the standing practice in `tests/test_fleet_analytics.py`. The live repo is exercised
too, but only for SHAPE and INVARIANTS — plus the three `why` transcripts the lane's ex-ante
names, which assert answer STRUCTURE rather than today's neighbour lists.

WHY `_load()` AND NOT A BARE IMPORT. `pythonpath = [".", "scripts", "deploy"]` would make a
bare `import file_purpose_graph` work, but loading by path keeps this module's name stable and
independent of collection order — the same reason `tests/test_fleet_analytics.py` loads by
spec.
"""

from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

_REPO = Path(__file__).resolve().parent.parent
_P = _REPO / "scripts" / "file_purpose_graph.py"
_MODNAME = "scripts.file_purpose_graph"


def _load():
    spec = importlib.util.spec_from_file_location(_MODNAME, _P)
    module = importlib.util.module_from_spec(spec)
    sys.modules[_MODNAME] = module
    spec.loader.exec_module(module)
    return module


fpg = _load()


