# A doc with the markers present but EMPTY — generating into it produces drift
# until --write fills the block (the natural "needs regeneration" state).
DOC_TEMPLATE = (
    "# Doc\n\n"
    "<!-- TOC:START -->\n"
    "<!-- TOC:END -->\n\n"
    "## Alpha [CORE]\n\n"
    "### Beta\n\n"
    "## Gamma\n"
)


def _write(tmp_path: Path, body: str) -> Path:
    f = tmp_path / "DOC.md"
    f.write_text(body, encoding="utf-8")
    return f


