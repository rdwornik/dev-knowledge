def test_generate_toc_nesting(tmp_path):
    f = _write(tmp_path, "# T\n\n## Purpose [CORE]\n\n### Layer model\n\n## Done\n")
    toc = generate_toc(f)
    assert "- [Purpose](#purpose-core)" in toc
    assert "  - [Layer model](#layer-model)" in toc
    assert "- [Done](#done)" in toc
    assert toc.endswith("<!-- generated by toc tool; do not edit by hand -->\n")


def test_generate_toc_dedup_anchor(tmp_path):
    f = _write(tmp_path, "## Foo\n\n## Foo\n")
    toc = generate_toc(f)
    assert "(#foo)" in toc
    assert "(#foo-1)" in toc


def test_generate_toc_idempotent(tmp_path):
    f = _write(tmp_path, "## A\n\n### B\n\n## C\n")
    assert generate_toc(f) == generate_toc(f)


